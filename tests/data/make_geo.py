"""Generates the Geo Fill and curve test meshes (tests/scripts/geo_fill.txt, curves.txt).

    python tests/data/make_geo.py

A flat strip of four unit quads in the z = 0 plane, facing +Z, x from -2 to 2:

    Q1 [-2,-1]  Q2 [-1,0]  |  Q3 [0,1]  Q4 [1,2]
    part Left              |  part Right
    material Red (Q1-Q3), Blue (Q4)

UVs (each quad 0.3 x 0.3, v 0.35..0.65):

- geo.obj: Q1 + Q2 one island in tile 1001 (u 0.1..0.7); Q3 and Q4 two islands in tile 1002
  (u 1.1..1.4 and 1.55..1.85).
- geo_moved.obj: the same, with the Q1 + Q2 island moved down to v 0.05..0.35.

Quads are written as quads, so each is one face for Geo Fill's Face. The materials are in geo.mtl.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def write(name, left_v0):
    v, vt, faces = [], [], []
    # (x0, u0, v0, material, part) per quad; Q1 and Q2 share their edge in UV space too.
    quads = [(-2, 0.1, left_v0, "Red", "Left"), (-1, 0.4, left_v0, "Red", "Left"),
             (0, 1.1, 0.35, "Red", "Right"), (1, 1.55, 0.35, "Blue", "Right")]
    lines = ["# Generated by make_geo.py", "mtllib geo.mtl", "vn 0 0 1"]
    part = None
    material = None
    for x0, u0, v0, mat, prt in quads:
        base_v, base_t = len(v) + 1, len(vt) + 1
        for (dx, dy) in [(0, 0), (1, 0), (1, 1), (0, 1)]:
            v.append((x0 + dx, dy - 0.5, 0.0))
            vt.append((u0 + 0.3 * dx, v0 + 0.3 * dy))
        faces.append((prt, mat, [(base_v + k, base_t + k) for k in range(4)]))
    lines += [f"v {x} {y} {z}" for x, y, z in v]
    lines += [f"vt {s:.6f} {t:.6f}" for s, t in vt]
    for prt, mat, f in faces:
        if prt != part:
            lines.append(f"o {prt}")
            part = prt
        if mat != material:
            lines.append(f"usemtl {mat}")
            material = mat
        lines.append("f " + " ".join(f"{a}/{b}/1" for a, b in f))
    with open(os.path.join(HERE, name), "w") as out:
        out.write("\n".join(lines) + "\n")


with open(os.path.join(HERE, "geo.mtl"), "w") as out:
    out.write("# Generated by make_geo.py\nnewmtl Red\nKd 0.8 0.1 0.1\nnewmtl Blue\nKd 0.1 0.1 0.8\n")
write("geo.obj", 0.35)
write("geo_moved.obj", 0.05)
